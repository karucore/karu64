#!/usr/bin/env python3
"""Build the ROM from assembly and emit/check its synthesizable Verilog.

The generated case table is the only encoded ROM source. Build intermediates
stay in --build-dir. Symbols are checked against the shared integration map.
SPDX-License-Identifier: BSD-2-Clause
"""
import argparse
import os
from pathlib import Path
import re
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build-dir', default='_build/dbg/rom')
    parser.add_argument('--xchain', default=os.environ.get('XCHAIN', 'riscv64-unknown-elf-'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    output = root / 'dbg/karudbg_rom.v'
    build = Path(args.build_dir).resolve()
    build.mkdir(parents=True, exist_ok=True)
    elf, binary = build / 'karudbg_rom.elf', build / 'karudbg_rom.bin'
    subprocess.run([args.xchain + 'gcc', '-march=rv64i_zicsr', '-mabi=lp64',
                    '-nostdlib', '-nostartfiles', '-Wl,--build-id=none,--no-relax',
                    '-T', str(root / 'dbg/rom/link.ld'),
                    str(root / 'dbg/rom/karudbg_rom.S'), '-o', str(elf)], check=True)
    subprocess.run([args.xchain + 'objcopy', '-O', 'binary', str(elf), str(binary)], check=True)
    symbols = subprocess.check_output([args.xchain + 'nm', '-n', str(elf)], text=True)
    defs = (root / 'dbg/karudbg_defs.vh').read_text()
    for symbol, macro in [('entry', 'ENTRY'), ('exception', 'EXCEPTION'), ('resume_dret', 'DRET')]:
        expected = int(re.search(r'`define KARUDBG_' + macro + r'\s+12\'h([0-9a-fA-F]+)', defs)[1], 16)
        actual = int(re.search(r'^([0-9a-fA-F]+)\s+\w\s+' + symbol + r'$', symbols, re.M)[1], 16)
        if actual != expected:
            raise SystemExit(f'{symbol}: assembled {actual:#x}, shared map {expected:#x}')
    data = binary.read_bytes()
    if len(data) & 3:
        raise SystemExit('ROM length is not instruction aligned')
    text = '''// Generated by dbg/rom/gen_rom.py from karudbg_rom.S; do not edit.
// Copyright 2016-2017 SiFive, Inc. SPDX-License-Identifier: Apache-2.0
// PULP riscv-dbg ROM adaptation; see assembly provenance and LICENSE.SiFive.
module karudbg_rom (
    input wire [11:0] addr_i,
    output reg [63:0] data_o
);
    wire unused_addr;
    assign unused_addr = &{1'b0, addr_i[2:0]};
    always @* begin
        data_o = 64'h00100073_00100073;
        case (addr_i[11:3])
'''
    for offset in range(0, len(data), 8):
        chunk = data[offset:offset+8]
        # A final single instruction is followed by a terminating EBREAK.
        if len(data[offset:offset+8]) == 4:
            chunk = data[offset:offset+4] + bytes.fromhex('73001000')
        text += f"            9'h{(0x800 + offset) >> 3:03x}: data_o = 64'h{int.from_bytes(chunk, 'little'):016x};\n"
    text += '''            default: ;
        endcase
    end
endmodule
'''
    if args.check:
        if not output.exists() or output.read_text() != text:
            raise SystemExit('Generated ROM differs; run make dbg-rom-generate')
        print('karudbg ROM regeneration: PASS')
    else:
        output.write_text(text)
        print(f'{output.relative_to(root)}: generated {len(data)} bytes')


if __name__ == '__main__':
    main()
