#!/usr/bin/env python3
"""Write the island ROM's key header for algorithm 0x04 (window.c built
with -DAUTH_ALG_SHA3 -DAUTH_KEY_HEADER="OUT").

    key_header.py KEYFILE OUT
    key_header.py --check-rom ROMBIN KEYFILE

The first form writes the header, and leaves an existing header untouched
when its content would not change, so that Make sees a new key and only a
new key. The second checks that the island ROM image ROMBIN holds the key
of KEYFILE, exactly once, and prints the key's fingerprint (the first 16
hexadecimal digits of SHA-256 of the 32 key bytes), never the key.

KEYFILE holds the 32-byte key as 64 hexadecimal digits (surrounding white
space ignored). OUT defines `static const uint8_t auth_key[32]`. The key is
never printed, and both files are written readable by the owner only.

test/dbg/auth_rom/test_key.txt is the simulation builds' key. It is PUBLIC
(it spells "karudbg-auth-v1 PUBLIC TEST KEY!") and protects nothing. The FPGA
image's key is generated once per build tree by dbg/fpga.mk.
"""
# SPDX-License-Identifier: BSD-2-Clause
import hashlib, os, re, sys
from pathlib import Path

def read_key(src):
    text = src.read_text().strip()
    if not re.fullmatch(r"[0-9a-fA-F]{64}", text):
        sys.exit(f"{src}: not a key of 64 hexadecimal digits ({len(text)} characters); content not shown")
    return bytes.fromhex(text)

if len(sys.argv) == 4 and sys.argv[1] == "--check-rom":
    rom, key = Path(sys.argv[2]).read_bytes(), read_key(Path(sys.argv[3]))
    found = rom.count(key)
    if found != 1:
        sys.exit(f"{sys.argv[3]} is not the key of {sys.argv[2]}: found {found} times in the ROM image")
    print(f"key {sys.argv[3]} matches {sys.argv[2]}; fingerprint {hashlib.sha256(key).hexdigest()[:16]}")
    sys.exit(0)
if len(sys.argv) != 3:
    sys.exit(__doc__)
src, dst = Path(sys.argv[1]), Path(sys.argv[2])
key = read_key(src)
rows = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in key[i:i + 8]) for i in range(0, 32, 8))
body = ("/* Generated by test/dbg/auth_rom/key_header.py from a key file. Secret unless\n"
        "   generated from test_key.txt; do not commit. */\n"
        "#ifndef KARU_AUTH_KEY_H\n#define KARU_AUTH_KEY_H\n#include <stdint.h>\n"
        f"static const uint8_t auth_key[32] = {{\n{rows} }};\n#endif\n")
if dst.exists() and dst.read_text() == body:
    print(f"{dst} is up to date (key not shown)")
    sys.exit(0)
old = os.umask(0o077)
try:
    tmp = dst.with_name(dst.name + ".tmp")
    tmp.write_text(body)
    tmp.replace(dst)
finally:
    os.umask(old)
print(f"wrote {dst} (key not shown)")
